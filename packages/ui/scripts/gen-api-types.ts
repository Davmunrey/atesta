/**
 * Generates an app's typed API client types (schema.d.ts) from its API's OpenAPI document.
 * Shared by every Atesta web app (ADR-017, "API conventions"). Usage, from the app's directory:
 * node node_modules/@atesta/ui/scripts/gen-api-types.ts <openapi.json> <schema.d.ts>.
 * Each app keeps a unit test that fails when its committed file is stale.
 */
import { realpathSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const HEADER = "// Generated by @atesta/ui/scripts/gen-api-types.ts from the API's openapi.json. Do not edit.\n\n";

/** The file's content for an OpenAPI document at `openapi` (a path or a file URL). */
export async function generate(openapi: string | URL): Promise<string> {
  const source = typeof openapi === "string" ? pathToFileURL(resolve(openapi)) : openapi;
  return HEADER + astToString(await openapiTS(source));
}

// The app runs this file through its node_modules link, so compare real paths.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [input, output] = process.argv.slice(2);
  if (!input || !output) throw new Error("usage: gen-api-types.ts <openapi.json> <schema.d.ts>");
  writeFileSync(output, await generate(input));
}
