"""Models and migrations agree; migrations are forward-only."""

from pathlib import Path

from alembic import command
from alembic.config import Config
from sqlalchemy.engine import URL

API_DIR = Path(__file__).resolve().parents[2]


def test_models_match_migrations(database: URL) -> None:
    config = Config(str(API_DIR / "alembic.ini"))
    config.set_main_option("sqlalchemy.url", database.render_as_string(hide_password=False))
    config.attributes["role"] = "atesta_owner"
    command.check(config)  # raises AutogenerateDiffsDetected on any drift


def test_migrations_import_no_application_code() -> None:
    for path in [
        *(API_DIR / "migrations" / "versions").glob("*.py"),
        API_DIR / "migrations" / "rls_v1.py",
    ]:
        assert "atesta_api" not in path.read_text(), path.name
