"""The statement of applicability CSV in the reader's language (i18n-complete spec)."""

import csv
import io

from fastapi.testclient import TestClient
from sqlalchemy import Engine

from .conftest import auth
from .test_members import org_with
from .test_overview import overview_catalog as overview_catalog
from .test_requirement_register import SCOPE, assessment, base
from .test_requirement_register import pack as pack


def _export(client: TestClient, superuser: Engine, pack: str, query: str) -> tuple[int, str]:
    org, subs = org_with(client, superuser)
    owner = auth(subs["owner"])
    client.post(base(org, pack) + "/scope", json={"axis_values": SCOPE}, headers=owner)
    client.post(base(org, pack) + "/register/m.cat", json=assessment(), headers=owner)
    response = client.get(base(org, pack) + "/applicability.csv" + query, headers=owner)
    return response.status_code, response.text


def _table(text: str) -> tuple[list[str], dict[str, list[str]]]:
    rows = [
        row for row in csv.reader(io.StringIO(text)) if row and not row[0].startswith(("#", "﻿#"))
    ]
    return rows[0], {row[0]: row for row in rows[1:]}


def test_the_export_is_spanish_by_default_with_a_byte_order_mark(
    client: TestClient, superuser: Engine, pack: str
) -> None:
    status, text = _export(client, superuser, pack, "")
    assert status == 200
    assert text.startswith("﻿# Generado por Atesta")
    header, rows = _table(text)
    assert header[:3] == ["Código", "Medida (título oficial)", "Decisión"]
    assert rows["m.cat"][2:4] == ["Aplica", "Sí"]
    assert rows["m.cat"][-1] == "Implantada"
    assert rows["m.none"][2:4] == ["Sin decidir", "No"]


def test_the_export_in_english_keeps_the_official_spanish_title(
    client: TestClient, superuser: Engine, pack: str
) -> None:
    status, text = _export(client, superuser, pack, "?lang=en")
    assert status == 200
    assert "# Generated by Atesta from the organization's own records. Not a certification." in text
    header, rows = _table(text)
    assert header[:3] == ["Code", "Measure (official Spanish title)", "Decision"]
    assert rows["m.cat"][1] == "Medida sintética"
    assert rows["m.cat"][2:4] == ["Applies", "Yes"]
    assert rows["m.cat"][-1] == "Implemented"


def test_an_unknown_language_is_refused(client: TestClient, superuser: Engine, pack: str) -> None:
    assert _export(client, superuser, pack, "?lang=fr")[0] == 422
