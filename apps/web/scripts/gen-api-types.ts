/**
 * Generates src/lib/api/schema.d.ts from openapi.json (written by the API's contract test).
 * Usage: pnpm gen:api. A unit test fails when the committed file is stale.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const DIR = new URL("../src/lib/api/", import.meta.url);
export const SCHEMA = fileURLToPath(new URL("schema.d.ts", DIR));
const HEADER = "// Generated by scripts/gen-api-types.ts from openapi.json. Do not edit.\n\n";

export async function generate(): Promise<string> {
  return HEADER + astToString(await openapiTS(new URL("openapi.json", DIR)));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(SCHEMA, await generate());
}
